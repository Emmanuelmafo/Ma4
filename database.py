import os
from sqlalchemy import create_engine, text

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)
if DATABASE_URL:
    engine = create_engine(DATABASE_URL, pool_pre_ping=True, pool_recycle=300)
else:
    engine = create_engine("sqlite:///smartshop.db", connect_args={"check_same_thread": False})

def run(sql, params=None):
    with engine.begin() as connection:
        connection.execute(text(sql), params or {})

def fetch_one(sql, params=None):
    with engine.connect() as connection:
        row = connection.execute(text(sql), params or {}).mappings().first()
        return dict(row) if row else None

def fetch_all(sql, params=None):
    with engine.connect() as connection:
        return [dict(row) for row in connection.execute(text(sql), params or {}).mappings().all()]

def insert(sql, params=None):
    with engine.begin() as connection:
        result = connection.execute(text(sql + " RETURNING id"), params or {})
        return result.scalar_one()

def init_db():
    statements = [
        """CREATE TABLE IF NOT EXISTS smartshop_products (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            name VARCHAR(200) NOT NULL UNIQUE, box_barcode VARCHAR(100) UNIQUE,
            item_barcode VARCHAR(100) UNIQUE, storage_quantity INTEGER NOT NULL DEFAULT 0 CHECK(storage_quantity >= 0),
            display_quantity INTEGER NOT NULL DEFAULT 0 CHECK(display_quantity >= 0),
            buying_price NUMERIC(12,2) NOT NULL DEFAULT 0, selling_price NUMERIC(12,2) NOT NULL DEFAULT 0,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)""",
        """CREATE TABLE IF NOT EXISTS smartshop_item_barcodes (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            product_id INTEGER NOT NULL REFERENCES smartshop_products(id),
            barcode VARCHAR(100) NOT NULL UNIQUE,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)""",
        """CREATE TABLE IF NOT EXISTS smartshop_stock_movements (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, product_id INTEGER NOT NULL REFERENCES smartshop_products(id),
            movement_type VARCHAR(30) NOT NULL, quantity INTEGER NOT NULL CHECK(quantity > 0),
            source_location VARCHAR(40), destination_location VARCHAR(40), note TEXT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)""",
        """CREATE TABLE IF NOT EXISTS smartshop_sales (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
            total_amount NUMERIC(12,2) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)""",
        """CREATE TABLE IF NOT EXISTS smartshop_sale_items (
            id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, sale_id INTEGER NOT NULL REFERENCES smartshop_sales(id),
            product_id INTEGER NOT NULL REFERENCES smartshop_products(id), quantity INTEGER NOT NULL CHECK(quantity > 0),
            unit_price NUMERIC(12,2) NOT NULL)"""
    ]
    if engine.dialect.name == "sqlite":
        statements = [s.replace("INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY", "INTEGER PRIMARY KEY AUTOINCREMENT") for s in statements]
    with engine.begin() as connection:
        for statement in statements:
            connection.execute(text(statement))
